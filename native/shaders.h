static const char *sg3_tone_fragment_shader =
    GLSL "in vec2 texcoord;out vec4 frag;uniform sampler2D sceneMap;uniform "
         "sampler2D bloomMap;uniform float bloomStrength;void "
         "main(){vec4 s=texture(sceneMap,texcoord);vec3 "
         "h=s.a>0.000001?s.rgb/"
         "s.a:vec3(0.0);vec3 "
         "glow=texture(bloomMap,texcoord).rgb*bloomStrength;h+=glow;s.a=max(s."
         "a,clamp(max(glow.r,max(glow.g,glow.b)),0.0,1.0));h=clamp(h,vec3(0.0),"
         "vec3(60000.0));vec3 "
         "mapped=clamp((h*(2.51*h+0.03))/"
         "(h*(2.43*h+0.59)+0.14),0.0,1.0);frag=vec4(pow(mapped,vec3(1.0/"
         "2.2))*s.a,s.a); }\n";

static const char *sg3_bloom_fragment_shader = GLSL
    "in vec2 texcoord;out vec4 frag;uniform sampler2D sourceMap;uniform vec4 "
    "stepAndExtract;vec3 sampleBright(vec2 uv){vec3 "
    "c=texture(sourceMap,uv).rgb;if(stepAndExtract.z>.5){float "
    "peak=max(c.r,max(c.g,c.b));c*=max(peak-1.0,0.0)/max(peak,.000001);}return "
    "c;}void main(){vec2 stepUV=stepAndExtract.xy;vec3 "
    "c=sampleBright(texcoord)*.227027027;for(int i=1;i<=4;i++){float "
    "w=i==1?.194594595:(i==2?.121621622:(i==3?.054054054:.016216216));c+=("
    "sampleBright(texcoord+stepUV*float(i))+sampleBright(texcoord-stepUV*float("
    "i)))*w;}frag=vec4(clamp(c,vec3(0.0),vec3(60000.0)),1.0); }\n";


static const char *sg3_fragment_shader = GLSL
    "in vec3 world;in vec3 nrm;in vec2 texcoord;in vec2 texcoord1;in vec4 "
    "tint;in vec4 shadowPosition;out vec4 frag;\n"
    "uniform vec3 eye;uniform vec3 lightDirection;uniform vec4 "
    "baseColor;uniform float metallic;uniform float roughness;uniform float "
    "exposure;uniform vec3 emissive;uniform vec4 uvSelectors;uniform float "
    "emissiveUV;uniform float normalScale;uniform float aoStrength;uniform int "
    "alphaMode;uniform float cutoff;uniform int unlit;\n"
    "uniform sampler2D baseMap;uniform sampler2D mrMap;uniform sampler2D "
    "normalMap;uniform sampler2D occlusionMap;uniform sampler2D "
    "emissiveMap;uniform sampler2D shadowMap;uniform samplerCube "
    "diffuseEnv;uniform samplerCube specularEnv;\n"
    "uniform int useBase;uniform int useMR;uniform int useNormal;uniform int "
    "useOcclusion;uniform int useEmissive;uniform int useEnv;\n"
    "const float PI=3.14159265359;vec3 linearize(vec3 c){return "
    "pow(max(c,vec3(0.0)),vec3(2.2));}\n"
    "vec3 fresnel(float c,vec3 f0){return "
    "f0+(1.0-f0)*pow(clamp(1.0-c,0.0,1.0),5.0);}\n"
    "vec3 studio(vec3 r){vec3 c=vec3(0.06,0.075,0.10);float "
    "a=pow(max(0.0,dot(r,normalize(vec3(-0.5,0.8,0.7)))),24.0);float "
    "b=pow(max(0.0,dot(r,normalize(vec3(0.8,0.25,-0.3)))),45.0);return "
    "c+vec3(1.4,1.2,0.95)*a+vec3(0.8,1.0,1.3)*b;}\n"
    /* Correct each PCF comparison to the receiver plane at the sampled texel
     * center. A normal-only bias cannot cover depth slope across neighboring
     * taps and produces periodic self-shadowing on large planar receivers. */
    "float shadow(vec3 n,vec3 l){vec3 "
    "q=shadowPosition.xyz/"
    "shadowPosition.w*0.5+0.5;vec3 "
    "dx=dFdx(q),dy=dFdy(q);if(q.x<0.0||q.x>1.0||q.y<0.0||q.y>1.0||q.z<0.0||"
    "q.z>1.0)return 1.0;float bias=max(0.0012*(1.0-dot(n,l)),0.00025);float "
    "v=0.0;float determinant=dx.x*dy.y-dx.y*dy.x;"
    "vec2 "
    "gradient=abs(determinant)>1e-12?vec2(dy.y*dx.z-dx.y*dy.z,dx.x*dy.z-dy.x*"
    "dx.z)/determinant:vec2(0.0);"
    "for(int x=-1;x<=1;x++){for(int y=-1;y<=1;y++){float "
    "d=texture(shadowMap,q.xy+vec2(float(x),float(y))/"
    "1024.0).r;v+=(q.z+dot(gradient,(floor(q.xy*1024.0)+vec2(0.5)+vec2(float(x)"
    ",float(y)))/1024.0-q.xy)-bias<=d)?1.0:0.0;}}return "
    "v/9.0;}\n" SG3_PUNCTUAL_SHADOW_GLSL
    "uniform int directionalEnabled;uniform vec4 pointPosRange[8];uniform vec4 "
    "pointColorIntensity[8];uniform "
    "vec4 spotPosRange;uniform vec4 spotColorIntensity;uniform vec4 "
    "spotDirectionInner;uniform float spotOuter;\n"
    "vec3 punctualBRDF(vec3 n,vec3 v,vec3 l,vec3 base,float metal,float "
    "rough){vec3 h=normalize(v+l);float "
    "nv=max(dot(n,v),.001),nl=max(dot(n,l),0.0),nh=max(dot(n,h),0.0),hv=max("
    "dot(h,v),0.0);float a=rough*rough,a2=a*a,den=nh*nh*(a2-1.0)+1.0;float "
    "D=a2/(PI*den*den),k=(rough+1.0)*(rough+1.0)/8.0;float "
    "G=nv/(nv*(1.0-k)+k)*nl/(nl*(1.0-k)+k);vec3 "
    "F=fresnel(hv,mix(vec3(.04),base,metal));return "
    "((1.0-F)*(1.0-metal)*base/PI+D*G*F/max(4.0*nv*nl,.001))*nl;}\n"
    "vec3 pointEnergy(vec4 posRange,vec4 colorIntensity,vec3 n,vec3 v,vec3 "
    "base,float metal,float rough){vec3 delta=posRange.xyz-world;float "
    "dist=max(length(delta),.01);if(colorIntensity.a<=0.0||dist>=posRange.a)"
    "return vec3(0.0);float "
    "fade=pow(clamp(1.0-pow(dist/posRange.a,4.0),0.0,1.0),2.0);return "
    "punctualBRDF(n,v,delta/"
    "dist,base,metal,rough)*colorIntensity.rgb*(colorIntensity.a/683.0)*fade/"
    "(4.0*PI*dist*dist);}\n"
    "void main(){vec4 base=baseColor*tint;if(useBase==1){vec4 "
    "t=texture(baseMap,uvSelectors.x<0.5?texcoord:texcoord1);base*=vec4("
    "linearize(t.rgb),t.a);}if(alphaMode==1&&base.a<cutoff)discard;if("
    "alphaMode<2)base.a=1.0;\n"
    "float metal=clamp(metallic,0.0,1.0);float "
    "rough=clamp(roughness,0.04,1.0);if(useMR==1){vec4 "
    "mr=texture(mrMap,uvSelectors.y<0.5?texcoord:texcoord1);rough=clamp(rough*"
    "mr.g,0.04,1.0);metal*=mr.b;}\n"
    "vec3 "
    "n=length(nrm)>0.000001?normalize(nrm):normalize(cross(dFdx(world),dFdy("
    "world)));if(!gl_FrontFacing)n=-n;if(useNormal==1){vec3 "
    "p1=dFdx(world),p2=dFdy(world);vec2 "
    "nuv=uvSelectors.z<0.5?texcoord:texcoord1;vec2 "
    "t1=dFdx(nuv),t2=dFdy(nuv);vec3 tr=p1*t2.y-p2*t1.y;vec3 "
    "br=-p1*t2.x+p2*t1.x;if(length(tr)>0.000001&&length(br)>0.000001){vec3 "
    "t=normalize(tr);vec3 b=normalize(br);vec3 "
    "m=texture(normalMap,nuv).xyz*2.0-1.0;m.xy*=normalScale;n=normalize(mat3(t,"
    "b,n)*m);}}\n"
    "vec3 v=normalize(eye-world);vec3 l=normalize(lightDirection);vec3 "
    "h=normalize(v+l);float nv=max(dot(n,v),0.001);float "
    "nl=max(dot(n,l),0.0);float nh=max(dot(n,h),0.0);float "
    "hv=max(dot(h,v),0.0);\n"
    "float a=rough*rough;float a2=a*a;float den=nh*nh*(a2-1.0)+1.0;float "
    "D=a2/(PI*den*den);float k=(rough+1.0)*(rough+1.0)/8.0;float "
    "G=(nv/(nv*(1.0-k)+k))*(nl/(nl*(1.0-k)+k));vec3 "
    "f0=mix(vec3(0.04),base.rgb,metal);vec3 F=fresnel(hv,f0);vec3 "
    "spec=D*G*F/max(4.0*nv*nl,0.001);vec3 kd=(1.0-F)*(1.0-metal);\n"
    "vec3 direct=(kd*base.rgb/PI+spec)*vec3(3.0,2.75,2.45)*nl*shadow(n,l);vec3 "
    "r=reflect(-v,n);vec3 "
    "diff=useEnv==1?texture(diffuseEnv,n).rgb:vec3(0.22,0.25,0.31);vec3 "
    "env=useEnv==1?textureLod(specularEnv,r,rough*7.0).rgb:studio(r);vec3 "
    "Fe=fresnel(nv,f0);float "
    "ao=useOcclusion==1?mix(1.0,texture(occlusionMap,uvSelectors.w<0.5?"
    "texcoord:texcoord1).r,aoStrength):1.0;vec3 "
    "ambient=((1.0-Fe)*(1.0-metal)*base.rgb*diff+env*Fe*(1.0-0.45*rough))*ao;\n"
    "vec3 "
    "emission=emissive;if(useEmissive==1)emission*=linearize(texture("
    "emissiveMap,emissiveUV<0.5?texcoord:texcoord1).rgb);vec3 "
    "punctual=vec3(0.0);for(int "
    "i=0;i<8;i++){float "
    "visibility=i==pointShadowIndex?sg3_point_visibility(world,n,normalize("
    "pointPosRange[i].xyz-world)):1.0;punctual+=pointEnergy(pointPosRange[i],"
    "pointColorIntensity[i],"
    "n,v,base.rgb,metal,rough)*visibility;}if(spotColorIntensity.a>0.0){vec3 "
    "toSurface=normalize(world-spotPosRange.xyz);float "
    "cone=smoothstep(spotOuter,spotDirectionInner.a,dot(toSurface,normalize("
    "spotDirectionInner.xyz)));float "
    "solid=max(.001,2.0*PI*(1.0-spotOuter));punctual+=pointEnergy(spotPosRange,"
    "spotColorIntensity,n,v,base.rgb,metal,rough)*cone*(4.0*PI/"
    "solid)*(spotShadowEnabled==1?sg3_spot_visibility(world,n,normalize("
    "spotPosRange.xyz-world)):1.0);}vec3 "
    "hdr=((unlit==1?base.rgb:direct*float(directionalEnabled)+ambient+punctual)"
    "+emission)*exposure;frag="
    "vec4("
    "clamp(hdr,vec3(0.0),vec3(60000.0)),base.a); }\n";
